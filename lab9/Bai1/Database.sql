CREATE TABLE Phong (
    MaPH NVARCHAR(50) PRIMARY KEY,
    LoaiP NVARCHAR(50),
    HangP NVARCHAR(50),
    DonGia FLOAT,
    TinhTrang NVARCHAR(50)
);

CREATE TABLE KH (
    SoCMT NVARCHAR(50) PRIMARY KEY,
    Hoten NVARCHAR(100),
    Gioitinh NVARCHAR(10)
);

CREATE TABLE ThueP (
    SoCMT NVARCHAR(50),
    MaPH NVARCHAR(50),
    NgayDen DATE,
    NgayDi DATE,
    TienSDDV FLOAT,
    PRIMARY KEY (SoCMT, MaPH),
    FOREIGN KEY (SoCMT) REFERENCES KH(SoCMT),
    FOREIGN KEY (MaPH) REFERENCES Phong(MaPH)
);

